HEADER = "# Generated by siade/bin/generate_errors_nomenclature.rb - do not edit by hand.\n".freeze

TARGETS = {
  entreprise: 'errors_entreprise.yml',
  particulier: 'errors_particulier.yml'
}.freeze

check_only = ARGV.include?('--check')
stale = []

TARGETS.each do |api, file_name|
  path = Rails.root.join('..', 'commons', 'data', file_name)
  content = HEADER + ErrorsNomenclature.new(api).to_h.to_yaml

  if check_only
    stale << path.to_s unless path.exist? && path.read == content
  else
    path.write(content)
    puts "Wrote #{path}"
  end
end

if stale.any?
  warn "Errors nomenclature out of date: #{stale.join(', ')}"
  warn 'Run siade/bin/generate_errors_nomenclature.rb'
  exit 1
end

puts 'Errors nomenclature up to date' if check_only
